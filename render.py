w("")
w("## Zonas macro")
w("")
w("| Líneas | Contenido | Notas |")
w("|---|---|---|")
w("| 1–27 | `<head>`, meta, manifest | |")
w("| 28–159 | `<style id=\"tw-minimal\">` | utilidades tipo Tailwind |")
