w("")
w("## Views HTML")
w("")
w("| Línea | ID |")
w("|---|---|")
for ln, v in d['views']:
    w(f"| {ln} | `{v}` |")
w("")
w("---")
w("")
w("## Índice de secciones JS")
w("")
w(f"153 secciones top-level. Formato: `rango` · nombre · (nº de funciones).")
w("")
w("| Rango | Sección | Fns |")
w("|---|---|---|")
for s in d['sections']:
    nf = len(s['funcs'])
    w(f"| `{s['line']}–{s['end']}` | **{s['name']}** | {nf if nf else ''} |")
w("")
w("---")
w("")
w("## Detalle por sección (funciones y sub-bloques)")
w("")
for s in d['sections']:
    if not s['funcs'] and not s['subs']:
        continue
    w(f"### `{s['line']}–{s['end']}` {s['name']}")
    if s['subs']:
        w("")
        w("Sub-bloques: " + " · ".join(f"`{ln}` {name}" for ln, _, name in s['subs']))
    if s['funcs']:
        w("")
        w("Funciones: " + ", ".join(f"`{name}`({ln})" for ln, name in s['funcs']))
    w("")
w("---")
w("")
w("## Constantes / feature flags top-level")
w("")
w("| Línea | Constante | Valor (inicio) |")
w("|---|---|---|")
for ln, name, val in d['consts']:
    val = val.replace('|', '\\|')
    if len(val) > 50: val = val[:50] + '…'
    w(f"| {ln} | `{name}` | `{val}` |")
w("")
w("---")
