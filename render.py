w("")
w("---")
w("")
w("## ⚠️ REGLA DE LECTURA (leer esto primero)")
w("")
w("**Nunca leer `index.html` entero.** Son ~300k tokens: consume la ventana completa en una sola lectura.")
w("")
w("Procedimiento obligatorio antes de tocar código:")
w("")
w("1. Buscar la sección en el índice de abajo → obtener rango `L_inicio–L_fin`")
w("2. Leer **solo** ese rango (`view` con `view_range`, o `sed -n 'X,Yp'`)")
w("3. Si no aparece en el índice: `grep -n \"nombreFuncion\" index.html` y leer ±40 líneas")
w("")
w("### 🚫 Líneas prohibidas (blobs de datos en una sola línea)")
w("")
w("Estas 3 líneas concentran **306 KB** — el 26% del archivo. Leerlas revienta el contexto:")
w("")
w("| Línea | Constante | Tamaño |")
w("|---|---|---|")
for ln, sz, n in d['big']:
    w(f"| **{ln}** | `{n}` | {sz//1024} KB |")
w("")
w("Para inspeccionarlas usar consultas puntuales, nunca lectura directa:")
w("")
w("```bash")
w("# ver solo las claves de ALL_DATA")
w("sed -n '2041p' index.html | grep -o '\"[A-Z0-9+]*\":{\"type\"' ")
